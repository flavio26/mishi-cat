const assert=require('node:assert/strict');
const M=require('../app/src/main/assets/model.js');
const now=Date.now();let s=M.createDefaultState(now);
assert.equal(s.name,'Mishi');assert.equal(s.stats.hunger,80);
assert.equal(M.deserialize('{',now).ok,false);
assert.equal(M.rename(s,'Luna').state.name,'Luna');
assert.equal(M.rename(s,' ').ok,false);
assert.equal(M.setFur(s,'negro').ok,false);
let fed=M.feed(s,now);assert.equal(fed.ok,true);assert(fed.state.stats.hunger>80);
assert.equal(M.feed(fed.state,now+100).ok,false);
let p=M.pet(s,now);assert.equal(p.ok,true);assert.equal(M.pet(p.state,now+100).ok,false);
let offline=M.tick(s,now+48*3600e3,{offline:true});assert.equal(offline.capped,true);assert.equal(offline.appliedMs,M.CONFIG.maxOfflineMs);assert(offline.state.stats.hunger>=15);
const resume=M.deserialize(M.serialize(offline.state),now+48*3600e3);assert.equal(resume.ok,true);
assert.equal(resume.state.activeGameId,null);
const start=M.startGame(s);assert.equal(start.ok,true);assert.equal(M.startGame(start.state).ok,false);
const end=M.finishGame(start.state,start.gameId,5);assert.equal(end.ok,true);assert.equal(end.state.activeGameId,null);assert(end.state.xp>0);
assert.equal(M.finishGame(end.state,start.gameId,5).ok,false);
const abort=M.abortGame(start.state,start.gameId);assert.equal(abort.ok,true);assert.equal(abort.state.activeGameId,null);
console.log('PASS 17 model checks: save, malformed, stats, cooldown, offline cap, game ID, unlock.');
